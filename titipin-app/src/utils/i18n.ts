export function useTranslation() {
  const language = useStore((s) => s.language) || 'id'
  const dict = translations[language] || translations.id

  const t = (key: keyof typeof translations.id, params?: Record<string, string | number>): string => {
    let str = dict[key] || translations.id[key] || key
    if (params) {
      Object.entries(params).forEach(([paramKey, paramVal]) => {
        str = str.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal))
      })
    }
    return str
  }

  return { t, language }
}
